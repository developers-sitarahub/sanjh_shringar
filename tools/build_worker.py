"""Generate server/entry.mjs (the file Wix runs): a tiny Cloudflare-style worker that gives the static
storefront clean URLs on Wix-managed headless hosting.

    /shop?c=under-3k   -> the Shop page (query string kept)
    /product?p=...     -> the Product page
    /about /contact /policies
    anything unknown   -> a small 404 page

Wix serves files that exist (assets/, *.html) before the worker runs, so old
.html links keep working. The page HTML is embedded here because fetching the
static file from inside the worker returns an empty body on Wix.

Usage:  python tools/build_worker.py      (also run by tools/build.py)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE, OUT = ROOT / "site", ROOT / "server"
PAGES = ["shop", "product", "about", "contact", "policies"]

NOT_FOUND = """<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Page not found | Sanjh Shringar</title><meta name="robots" content="noindex"><link rel="icon" href="/assets/favicon.png">
<link rel="stylesheet" href="/assets/styles.css"></head><body><main class="container" style="min-height:70vh;display:grid;place-content:center;text-align:center;gap:18px">
<h1 class="x-h2">Page not <em>found</em></h1><p class="lead" style="margin-inline:auto">This page has moved or no longer exists.</p>
<p><a class="btn btn--primary" href="/">Back to the homepage</a></p></main></body></html>"""

TEMPLATE = """// GENERATED by tools/build_worker.py; edit that file, not this one.
// Clean URLs for the Sanjh Shringar storefront on Wix-managed headless hosting.
const PAGES = __PAGES__;
const NOT_FOUND = __NOT_FOUND__;
const HEADERS = { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "public, max-age=0, must-revalidate" };

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const path = url.pathname.replace(/\\/+$/, "") || "/";
    const name = path === "/" ? "index" : path.slice(1);
    if (Object.prototype.hasOwnProperty.call(PAGES, name)) {
      return new Response(request.method === "HEAD" ? null : PAGES[name], { status: 200, headers: HEADERS });
    }
    return new Response(request.method === "HEAD" ? null : NOT_FOUND, { status: 404, headers: HEADERS });
  }
};
"""


def build() -> None:
    pages = {name: (SITE / f"{name}.html").read_text(encoding="utf-8") for name in PAGES + ["index"]}
    js = TEMPLATE.replace("__PAGES__", json.dumps(pages, ensure_ascii=False)).replace("__NOT_FOUND__", json.dumps(NOT_FOUND))
    OUT.mkdir(exist_ok=True)
    (OUT / "entry.mjs").write_text(js, encoding="utf-8", newline="\n")
    print("built server/entry.mjs", f"({len(js) // 1024} KB)")


if __name__ == "__main__":
    build()
